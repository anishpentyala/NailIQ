"""Refresh generated evidence in the NailIQ vault; preserve all authored notes."""
import argparse
import hashlib
import json
from datetime import datetime
from pathlib import Path
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT.parent.parent / 'Obsidian Vaults' / 'NailIQ'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--vault', type=Path, default=DEFAULT)
    args = parser.parse_args()
    vault = args.vault
    stamp = datetime.now().strftime('%Y-%m-%d_%H%M%S_%f')
    out = vault / 'Sources' / stamp
    out.mkdir(parents=True)

    def git(*arguments):
        return subprocess.check_output(['git', *arguments], cwd=ROOT).decode('utf-8', errors='replace')

    def write(name, body):
        (out / name).write_text(body, encoding='utf-8')

    files = sorted(set(git('ls-files', '--cached', '--others', '--exclude-standard').splitlines()))
    excluded = {'.env', '.env.local', '.env.production'}
    files = [p for p in files if (ROOT / p).is_file() and Path(p).name not in excluded
             and Path(p).suffix.lower() not in {'.db', '.sqlite', '.log', '.err'}
             and not p.startswith('data/real_eval')]
    write('Git History.md', '# Complete reachable Git history\n\n```text\n' + git('log', '--all', '--reverse', '--date=iso-strict', '--format=%H%nDate: %ad%nAuthor: %an%n%s%n%b', '--stat') + '\n```\n')
    write('Working Tree.md', '# Working tree at capture\n\n```text\n' + git('status', '--short') + '\n```\n\nThese entries are uncommitted, not evidence of a completed test run.\n')
    write('Working Tree Changes.patch', git('diff', 'HEAD', '--', *[p for p in files if not p.startswith('.claude/')]))
    manifest = []
    with zipfile.ZipFile(out / 'Project source and artwork.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
        for relative in files:
            path = ROOT / relative
            archive.write(path, relative)
            manifest.append({'path': relative, 'bytes': path.stat().st_size, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    for relative in ['README.md', 'CLAUDE.md', 'AGENTS.md', 'PRIVACY.md', 'ATTRIBUTION.md', 'data/DATASETS_DIVERSITY.md', 'data/raw/LICENSES.md', 'docs/learn_diagram_prompts.md']:
        path = ROOT / relative
        if path.exists():
            write(relative.replace('/', ' - '), '> Historical source snapshot. Claims are preserved as written; consult current-state notes for corrections.\n\n' + path.read_text(encoding='utf-8'))
    for path in (ROOT / 'ml/models').glob('*.json'):
        write(path.name, path.read_text(encoding='utf-8'))
    write('Manifest.json', json.dumps(manifest, indent=2))
    inventory = '# Artifact inventory\n\nSource files and artwork are preserved in the adjacent ZIP. Data, weights, private photos, environments and secrets stay in their original locations.\n\n'
    for item in manifest:
        path = ROOT / item['path']
        inventory += f"- [{item['path']}](<{path.as_posix()}>) ({item['bytes']:,} bytes)\n"
    inventory += '\n## Model weights on disk (not copied)\n\n'
    for path in (ROOT / 'ml/models').glob('*.pt'):
        inventory += f'- [{path.name}](<{path.as_posix()}>) ({path.stat().st_size:,} bytes)\n'
    write('Artifact Inventory.md', inventory)
    (vault / 'Latest Evidence.md').write_text(f'# Latest evidence\n\nCaptured {stamp}.\n\n- [[Sources/{stamp}/Git History]]\n- [[Sources/{stamp}/Working Tree]]\n- [[Sources/{stamp}/Artifact Inventory]]\n- [[Sources/{stamp}/README]]\n- [[Sources/{stamp}/CLAUDE]]\n\n[Complete source and artwork snapshot](Sources/{stamp}/Project%20source%20and%20artwork.zip)\n\nGenerated by `scripts/sync_obsidian_vault.py`. Authored history and decisions require a human or agent update under [[Vault Maintenance]].\n', encoding='utf-8')
    print(json.dumps({'vault': str(vault), 'snapshot': stamp, 'files_archived': len(files)}))


if __name__ == '__main__':
    main()
